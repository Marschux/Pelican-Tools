/** Builds a valheim world metadata file: two int32 headers, then two length-prefixed strings. */
function fwl(string $name, string $seed): string
{
    return pack('V', 0) . pack('V', 35)
        . chr(strlen($name)) . $name
        . chr(strlen($seed)) . $seed
        . pack('V', 123456) . pack('P', 42) . pack('V', 2);
}

assert(FwlSeedParser::parse(fwl('Dedicated', 'HHcLC5acQt')) === 'HHcLC5acQt');
assert(FwlSeedParser::parse(fwl('a', 'x')) === 'x', 'shortest possible name and seed');
assert(FwlSeedParser::parse(fwl(str_repeat('w', 64), 'seed1')) === 'seed1', 'name at the limit');

// truncated, empty and nonsense input must yield null, never a garbage seed
assert(FwlSeedParser::parse('') === null);
assert(FwlSeedParser::parse(substr(fwl('Dedicated', 'HHcLC5acQt'), 0, 11)) === null, 'cut off before the seed');
assert(FwlSeedParser::parse(pack('V', 0) . pack('V', 35) . chr(0) . 'xx') === null, 'zero-length name');
assert(FwlSeedParser::parse(pack('V', 0) . pack('V', 35) . chr(200) . str_repeat('x', 300)) === null, 'name length beyond the cap');

// a changed 1.0 header shifts everything: the bytes at the seed offset are not printable,
// and that must read as "cannot tell" rather than as a seed
assert(FwlSeedParser::parse(pack('V', 0) . pack('V', 35) . chr(4) . 'name' . chr(5) . chr(0) . chr(1) . chr(2) . chr(3) . chr(4)) === null, 'binary where the seed should be');

/** Minimal NBT writer: a named tag is a type byte, a u16 name length, the name, then its payload. */
function tag(int $type, string $name, string $payload): string
{
    return chr($type) . pack('n', strlen($name)) . $name . $payload;
}

function nbtString(string $value): string
{
    return pack('n', strlen($value)) . $value;
}

function nbtCompound(string ...$tags): string
{
    return implode('', $tags) . "\x00";
}

// minecraft 26.1+: the seed sits in world_gen_settings.dat, after a nested dimensions compound -
// shaped like a real file generated by paper 26.2
$modern = gzencode(tag(10, '', nbtCompound(
    tag(3, 'DataVersion', pack('N', 4903)),
    tag(10, 'data', nbtCompound(
        tag(1, 'generate_structures', chr(1)),
        tag(10, 'dimensions', nbtCompound(
            tag(10, 'minecraft:overworld', nbtCompound(tag(8, 'type', nbtString('minecraft:overworld')))),
        )),
        tag(4, 'seed', pack('J', -1234567890123456789)),
    )),
)));
assert(NbtReader::find($modern, ['data', 'seed']) === -1234567890123456789, 'negative long behind a nested compound');
assert(NbtReader::find($modern, ['DataVersion']) === 4903);

// before 26.1 the seed lived in level.dat, behind lists and arrays that have to be skipped
$legacy = gzencode(tag(10, '', nbtCompound(tag(10, 'Data', nbtCompound(
    tag(9, 'ServerBrands', chr(8) . pack('N', 2) . nbtString('paper') . nbtString('vanilla')),
    tag(11, 'ids', pack('N', 2) . pack('N', 1) . pack('N', 2)),
    tag(8, 'LevelName', nbtString('world')),
    tag(10, 'WorldGenSettings', nbtCompound(tag(4, 'seed', pack('J', -2070977467)))),
)))));
assert(NbtReader::find($legacy, ['Data', 'WorldGenSettings', 'seed']) === -2070977467, 'skips a list and an int array on the way');
assert(NbtReader::find($legacy, ['Data', 'LevelName']) === 'world');
assert(NbtReader::find(gzdecode($legacy), ['Data', 'LevelName']) === 'world', 'uncompressed nbt reads the same');

// wrong layout, a non-scalar target, garbage and truncation must all mean "cannot tell"
assert(NbtReader::find($modern, ['Data', 'WorldGenSettings', 'seed']) === null, 'old path against the new layout');
assert(NbtReader::find($legacy, ['Data', 'WorldGenSettings']) === null, 'a compound is not a seed');
assert(NbtReader::find('', ['data']) === null);
assert(NbtReader::find('not nbt at all', ['data']) === null);
assert(NbtReader::find(substr(gzdecode($legacy), 0, 40), ['Data', 'WorldGenSettings', 'seed']) === null, 'cut off mid-file');

// server names carry markup the panel cannot render, and it must not leak into the ui
assert((new QueryResult(hostname: '<color=lime>Tormax</color>', players: 0, maxPlayers: 10))->hostname === 'Tormax');
assert(QueryResult::plain('<color=#ff0000>Rot</color> Server') === 'Rot Server');
assert(QueryResult::plain('<b>Bold</b> and <i>italic</i>') === 'Bold and italic');
assert(QueryResult::plain("\u{00a7}aGruen\u{00a7}r Server") === 'Gruen Server', 'minecraft colour codes');
assert(QueryResult::plain('Ganz normal') === 'Ganz normal', 'untouched when there is no markup');
assert(QueryResult::plain('A <bogus>tag</bogus> stays') === 'A <bogus>tag</bogus> stays', 'only known tags are stripped');

// the icon is not offered as a toggle: nothing renders a data uri in a stat block
assert(!in_array('icon', QueryResult::FIELDS, true));

// os was dropped entirely - not read from A2S, not offered, not in the api output
assert(!in_array('os', QueryResult::FIELDS, true));

// a schema only offers fields its protocol can actually report - the admin field list is
// built from this, and a checkbox for something a game can never show is worse than none
$sourceFields = (new SourceSchema())->supportedFields();
assert(in_array('map', $sourceFields, true) && in_array('secure', $sourceFields, true));
assert(!in_array('seed', $sourceFields, true), 'source games have no readable seed');

// cs2 rcon status gives the real counts, A2S is one bot short
assert(SourceSchema::parseStatusCounts("[Client] players  : 1 humans, 9 bots (0 max) (not hibernating)") === [1, 9]);
assert(SourceSchema::parseStatusCounts("players  : 0 humans, 1 bot (16 max)") === [0, 1]);
assert(SourceSchema::parseStatusCounts("Bad rcon_password.") === null);
$counted = (new QueryResult('x', 10, 16, bots: 8))->withCounts(10, 9);
assert($counted->players === 10 && $counted->bots === 9 && $counted->maxPlayers === 16);

// cs2 only advertises "secure" as keyword, the mode comes from the egg's variables
assert(SourceSchema::cs2Mode('0', '1') === 'Competitive' && SourceSchema::cs2Mode('1', '2') === 'Deathmatch');
assert(SourceSchema::cs2Mode(null, null) === null, 'other source games keep what A2S reports');

// goldsrc inherits source's field list rather than redeclaring it
assert((new GoldSourceSchema())->supportedFields() === $sourceFields);

$mcFields = (new MinecraftJavaSchema())->supportedFields();
assert(!in_array('bots', $mcFields, true), 'minecraft has no bot concept');
assert(in_array('seed', $mcFields, true) && in_array('gameMode', $mcFields, true) && in_array('whitelist', $mcFields, true));
assert(!in_array('whitelist', $sourceFields, true), 'whitelist is a minecraft concept');
assert(!in_array('map', $mcFields, true), 'the level name says nothing a player needs, the seed replaced it');

// valheim answers A2S, but several of the fields that come back are meaningless or wrong for
// it - these must never be offered, no matter what the underlying protocol technically returns
$valheimFields = (new ValheimSchema())->supportedFields();
foreach (['map', 'bots', 'version', 'secure', 'gameMode', 'os'] as $wrong) {
    assert(!in_array($wrong, $valheimFields, true), "valheim must not offer $wrong");
}
assert(in_array('seed', $valheimFields, true) && in_array('world', $valheimFields, true));
assert(!in_array('world', (new SourceSchema())->supportedFields(), true), 'only valheim knows its world name');

// every field a schema claims to support must be a real QueryResult field, and every schema
// must be resolvable through get() - otherwise the admin could offer a checkbox that always
// throws or silently does nothing
foreach ([new SourceSchema(), new GoldSourceSchema(), new MinecraftJavaSchema(), new ValheimSchema()] as $schema) {
    foreach ($schema->supportedFields() as $field) {
        assert(in_array($field, QueryResult::FIELDS, true), get_class($schema) . " supports unknown field $field");
    }
}

// "password" comes from a startup variable, not the protocol, but it is still the schema that
// offers it: only games with a join password list it - on Minecraft or TeamSpeak the checkbox
// could never show anything
foreach ([new SourceSchema(), new GoldSourceSchema(), new ValheimSchema()] as $schema) {
    assert(in_array('password', $schema->supportedFields(), true), get_class($schema) . ' has join passwords');
}
foreach ([new MinecraftJavaSchema(), new TeamSpeakSchema()] as $schema) {
    assert(!in_array('password', $schema->supportedFields(), true), get_class($schema) . ' has no join password to show');
}

// regression: the admin's create form asks for a schema before any type is chosen yet, so
// get(null) must return null quietly - a non-nullable parameter here previously turned into a
// fatal TypeError the instant the "new game query" form opened
$service = new QueryTypeService();
$service->register(new SourceSchema());
assert($service->get(null) === null);
assert($service->get('source') !== null);
assert($service->get('does-not-exist') === null);

// with()/withSeed()/withPassword() must produce independent copies rather than mutating the
// original - these are readonly objects shared through the cache, so a copy that leaked back
// into the original would corrupt every other reader of that cache entry
$base = new QueryResult(hostname: 'X', players: 1, maxPlayers: 2);
$withSeed = $base->withSeed('abc');
assert($base->seed === null && $withSeed->seed === 'abc');
assert($withSeed->withWorld('Dedicated')->world === 'Dedicated' && $withSeed->withWorld('Dedicated')->seed === 'abc');

$withPassword = $withSeed->withPassword('secret');
assert($withSeed->password === null, 'the earlier copy must stay untouched');
assert($withPassword->seed === 'abc' && $withPassword->password === 'secret', 'earlier overrides must survive a later one');

$withMode = $withPassword->withGameMode('survival');
assert($withPassword->gameMode === null && $withMode->gameMode === 'survival');
assert($withMode->seed === 'abc' && $withMode->password === 'secret');

// false is an answer ("whitelist off"), null is not - both have to survive the copy distinctly
$whitelistOff = $withMode->withWhitelist(false);
assert($withMode->whitelist === null && $whitelistOff->whitelist === false);
assert($whitelistOff->gameMode === 'survival' && $whitelistOff->toArray()['whitelist'] === false);

// re-running the constructor through with() must not double-mangle an already-clean hostname
assert((new QueryResult(hostname: '<color=lime>Already</color>', players: 0, maxPlayers: 0))->withSeed('x')->hostname === 'Already');

// crossplay servers never answer A2S, so the player count comes out of their own log
// plain quotes, as valheim writes them - inside single-quoted php strings a \" would be a literal
// backslash, which no real log line has and which the parser rightly never matched
$log = [
    '09/10/2026 22:35:40: Session "<color=lime>Tormax</color>" registered with join code 001340',
    '09/10/2026 22:35:44: Session "<color=lime>Tormax</color>" with join code 688911 and IP 89.245.16.209:2456 is active with 0 player(s)',
    '09/10/2026 22:43:19: Got character ZDOID from Ichfrauson : 3090414758:5',
    '09/10/2026 22:44:02: Session "<color=lime>Tormax</color>" with join code 688911 and IP 89.245.16.209:2456 is active with 2 player(s)',
];

assert(ValheimLogParser::players($log) === 2, 'the newest count wins, not the first');
assert(ValheimLogParser::hostname($log) === 'Tormax', 'markup is stripped here too');
assert(ValheimLogParser::players([]) === null, 'empty log is not zero players');
assert(ValheimLogParser::players(['nothing to see here']) === null);

// only the registration line present: no count yet
assert(ValheimLogParser::players([$log[0]]) === null);

